-- Step 1: Switch to an administrative role
USE ROLE ACCOUNTADMIN;

USE WAREHOUSE ETL_WH;

-- Step 2: Create database and drop default PUBLIC schema
CREATE DATABASE IF NOT EXISTS ANALYTICS_PROD;
USE DATABASE ANALYTICS_PROD;

DROP SCHEMA IF EXISTS ANALYTICS_PROD.PUBLIC;

-- Step 3: Create the single target schema
CREATE SCHEMA IF NOT EXISTS CORE;


-- Step 4: Create structured access roles
USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS ANALYTICS_ADMIN_ROLE;  -- Full DDL/DML
CREATE ROLE IF NOT EXISTS ANALYTICS_WRITE_ROLE;  -- Ingestion / Transformation (ETL)
CREATE ROLE IF NOT EXISTS ANALYTICS_READ_ROLE;   -- Query / BI Reporting

-- Establish standard role hierarchy up to SYSADMIN
GRANT ROLE ANALYTICS_READ_ROLE  TO ROLE ANALYTICS_WRITE_ROLE;
GRANT ROLE ANALYTICS_WRITE_ROLE TO ROLE ANALYTICS_ADMIN_ROLE;
GRANT ROLE ANALYTICS_ADMIN_ROLE TO ROLE SYSADMIN;


-- Step 5: Grant Warehouse and Database USAGE
USE ROLE SECURITYADMIN;

-- Allow roles to use the ETL_WH warehouse
GRANT USAGE ON WAREHOUSE ETL_WH TO ROLE ANALYTICS_READ_ROLE;

-- Database-level access
GRANT USAGE ON DATABASE ANALYTICS_PROD TO ROLE ANALYTICS_READ_ROLE;


-- Step 6: Grant Schema and Object Privileges on the single schema

-- 6A: Read Privileges (Read Role)
GRANT USAGE ON SCHEMA CORE TO ROLE ANALYTICS_READ_ROLE;

-- Current objects
GRANT SELECT ON ALL TABLES IN SCHEMA CORE TO ROLE ANALYTICS_READ_ROLE;
GRANT SELECT ON ALL VIEWS  IN SCHEMA CORE TO ROLE ANALYTICS_READ_ROLE;

-- Future objects
GRANT SELECT ON FUTURE TABLES IN SCHEMA CORE TO ROLE ANALYTICS_READ_ROLE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA CORE TO ROLE ANALYTICS_READ_ROLE;


-- 6B: Write Privileges (ETL Role)
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA CORE TO ROLE ANALYTICS_WRITE_ROLE;

-- Current tables DML
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA CORE TO ROLE ANALYTICS_WRITE_ROLE;

-- Future tables DML
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA CORE TO ROLE ANALYTICS_WRITE_ROLE;


-- 6C: Admin Privileges (Full schema control)
GRANT ALL PRIVILEGES ON SCHEMA CORE TO ROLE ANALYTICS_ADMIN_ROLE;


