-- ============================================================================
-- S3 Storage Integration & External Stage Setup for Snowflake
-- ============================================================================

-- STEP 1: Create the Storage Integration (Requires ACCOUNTADMIN)
USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE STORAGE INTEGRATION S3_NAT_DATA
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::351578878554:role/snowflake-s3-role'
  STORAGE_ALLOWED_LOCATIONS = ('s3://nat-data-source-351578878554-us-east-1-an/');

-- STEP 2: Grant Integration Usage to the ETL Write Role
GRANT USAGE ON INTEGRATION S3_NAT_DATA TO ROLE ANALYTICS_WRITE_ROLE;
GRANT USAGE ON INTEGRATION S3_NAT_DATA TO ROLE ANALYTICS_ADMIN_ROLE;

-- STEP 3: Retrieve Snowflake's IAM User ARN and External ID
-- Copy these two values into your AWS IAM Role Trust Relationship!
DESC INTEGRATION S3_NAT_DATA;
-- Expected output:
-- STORAGE_AWS_IAM_USER_ARN: arn:aws:iam::867345910763:user/b01j1000-s
-- STORAGE_AWS_EXTERNAL_ID:  HXB50797_SFCRole=5_RtSeKxMOLWriwl7F7fUen7e84sM=

-- STEP 4: Grant Permissions to Create Formats & Stages in Target Schema
GRANT CREATE FILE FORMAT, CREATE STAGE ON SCHEMA ANALYTICS_PROD.CORE TO ROLE ANALYTICS_WRITE_ROLE;

-- STEP 5: Switch to the ETL Role and Target Database/Schema
USE ROLE ANALYTICS_WRITE_ROLE;
USE WAREHOUSE ETL_WH;
USE DATABASE ANALYTICS_PROD;
USE SCHEMA CORE;

-- STEP 6: Create Reusable Parquet File Format
CREATE FILE FORMAT IF NOT EXISTS PARQUET_FORMAT
  TYPE = PARQUET
  COMPRESSION = AUTO;

-- STEP 7: Create the External Stage pointing to the S3 bucket
CREATE STAGE IF NOT EXISTS S3_PARQUET_STAGE
  STORAGE_INTEGRATION = S3_NAT_DATA
  URL = 's3://nat-data-source-351578878554-us-east-1-an/'
  FILE_FORMAT = PARQUET_FORMAT;

-- STEP 8: Test Stage Connectivity (lists 8 TPC-H Parquet files)
LIST @S3_PARQUET_STAGE;

-- STEP 9: Create Target RAW Landing Tables (via Schema Inference)
CREATE TABLE IF NOT EXISTS RAW_CUSTOMER
  USING TEMPLATE (
    SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*))
    FROM TABLE(INFER_SCHEMA(LOCATION=>'@S3_PARQUET_STAGE/customer.parquet', FILE_FORMAT=>'PARQUET_FORMAT'))
  );

CREATE TABLE IF NOT EXISTS RAW_LINEITEM
